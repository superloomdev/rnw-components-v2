// Info: Writes the fidelity census sheet from machine output only: the
// census runs' findings (`_test/census/test-results/census/*.json`, written
// by `_test/census/census.spec.js`). Every number and every row is the scripts'; the
// reasoning tier adds its classification beside the sheet, never in it.
//
// Usage: node scripts/census.js [--out <path>]   (default: ../__dev__/evidence/0160/census-m1.md)

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { REPO_ROOT } from './lib/components.js';

const outIndex = process.argv.indexOf('--out');
const OUT = outIndex === -1 ? resolve(REPO_ROOT, '..', '__dev__', 'evidence', '0160', 'census-m1.md') : resolve(process.argv[outIndex + 1]);
const RUNS = join(REPO_ROOT, '_test', 'census', 'test-results', 'census');
// The perceptual budget a state is held to (the roster's default)
const BUDGET = 2;



const runs = existsSync(RUNS) ? readdirSync(RUNS).filter(function (file) {
  return file.endsWith('.json');
}).sort().map(function (file) {
  return JSON.parse(readFileSync(join(RUNS, file), 'utf8'));
}) : [];

const lines = [];
lines.push('# Fidelity census - milestone 1');
lines.push('');
lines.push('Generated by `scripts/census.js` from `_test/census/census.spec.js` runs and the second reference\'s component token files. No row is typed.');
lines.push('');
lines.push('## Summary by run');
lines.push('');
lines.push('| Row | Reference | Scheme | States measured | Disagreements | States over ' + BUDGET + '% perceptual | Unmeasured | Errors |');
lines.push('|---|---|---|---|---|---|---|---|');
let total = 0;
for (const run of runs) {
  const over = Object.keys(run.perceptual).filter(function (key) {
    return run.perceptual[key] > BUDGET;
  });
  total += run.lines.length;
  lines.push('| ' + run.component + ' | ' + run.set + ' | ' + run.scheme + ' | ' + run.states + ' | ' + run.lines.length + ' | ' + over.length + ' | ' + run.unmeasured.length + ' | ' + run.errors.length + ' |');
}
lines.push('');
lines.push('Total disagreements: ' + total + '.');
lines.push('');

lines.push('## Disagreements');
lines.push('');
for (const run of runs) {
  if (run.lines.length === 0) {
    continue;
  }
  lines.push('### ' + run.component + ' / ' + run.set + ' / ' + run.scheme);
  lines.push('');
  for (const line of run.lines) {
    lines.push('- ' + line);
  }
  lines.push('');
}

lines.push('## Perceptual ratio per state (percent of pixels; budget ' + BUDGET + '%)');
lines.push('');
for (const run of runs) {
  const keys = Object.keys(run.perceptual);
  if (keys.length === 0) {
    continue;
  }
  lines.push('### ' + run.component + ' / ' + run.set + ' / ' + run.scheme);
  lines.push('');
  lines.push(keys.map(function (key) {
    return key + ' ' + run.perceptual[key] + (run.perceptual[key] > BUDGET ? ' (over)' : '');
  }).join('; '));
  lines.push('');
}


writeFileSync(OUT, lines.join('\n') + '\n');
process.stdout.write('census: ' + runs.length + ' run(s), ' + total + ' disagreement(s) -> ' + OUT + '\n');
