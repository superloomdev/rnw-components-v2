// Info: Writes `_test/harness/manifest.js`, the import list the browser bundles
// need: every component's sample states and measurement reference, keyed by
// name, plus the roster rows the showcase reads. Generated before every bundle (never committed) so the
// browser tier discovers components the same way the Node gates do.
//
// Usage: node scripts/manifest-generate.js

import { writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

import { REPO_ROOT, discoverComponents, getRoster } from './lib/components.js';

const OUT = join(REPO_ROOT, '_test', 'harness', 'manifest.js');
const components = await discoverComponents();
const roster = getRoster();
const rows = {};
for (const row of roster.rows) {
  rows[row.name] = row;
}

const lines = ['// Generated by scripts/manifest-generate.js. Not committed.', ''];
for (const component of components) {
  const path = relative(join(REPO_ROOT, '_test', 'harness'), component.files.sample).split('\\').join('/');
  lines.push('import sample_' + component.name + ' from \'' + path + '\';');
}
const referenced = components.filter(function (component) {
  return component.reference !== null;
});
for (const component of referenced) {
  const path = relative(join(REPO_ROOT, '_test', 'harness'), component.files.reference).split('\\').join('/');
  lines.push('import reference_' + component.name + ' from \'' + path + '\';');
}
lines.push('');
lines.push('export const references = {');
lines.push(referenced.map(function (component) {
  return '  ' + component.name + ': reference_' + component.name;
}).join(',\n'));
lines.push('};');
lines.push('');
lines.push('export const samples = {');
lines.push(components.map(function (component) {
  return '  ' + component.name + ': sample_' + component.name;
}).join(',\n'));
lines.push('};');
lines.push('');
lines.push('export const rows = ' + JSON.stringify(components.reduce(function (out, component) {
  const row = rows[component.name];
  out[component.name] = { family: row.family, tier: row.tier, reference: row.reference, enums: row.enums, diff_budget: row.diff_budget, flags: row.flags };
  return out;
}, {}), null, 2) + ';');
lines.push('');
writeFileSync(OUT, lines.join('\n'));
process.stdout.write('manifest: ' + components.length + ' component(s) -> ' + relative(REPO_ROOT, OUT) + '\n');
